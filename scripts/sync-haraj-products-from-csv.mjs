#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs"
import { resolve, dirname, basename } from "node:path"

const csvArg = process.argv[2] && !process.argv[2].startsWith("--") ? process.argv[2] : "haraj.csv"
const outputArg = process.argv[3] && !process.argv[3].startsWith("--") ? process.argv[3] : "lib/server/haraj-bank.ts"
const imageDirArg =
  process.argv[4] && !process.argv[4].startsWith("--") ? process.argv[4] : "public/images/haraj"

const csvPath = resolve(process.cwd(), csvArg)
const outputPath = resolve(process.cwd(), outputArg)
const imageDirPath = resolve(process.cwd(), imageDirArg)

function normalizeEasternArabicDigits(value) {
  return value
    .replace(/[٠-٩]/g, (digit) => String(digit.charCodeAt(0) - 0x660))
    .replace(/[۰-۹]/g, (digit) => String(digit.charCodeAt(0) - 0x6f0))
}

function parseNumber(value) {
  const normalized = normalizeEasternArabicDigits(String(value ?? "").trim())
    .replace(/٫/g, ".")
    .replace(/[٬،,]/g, "")
    .replace(/\s+/g, "")
  if (!normalized) {
    return Number.NaN
  }
  return Number(normalized)
}

function parseCsv(content) {
  const rows = []
  let row = []
  let field = ""
  let inQuotes = false

  for (let index = 0; index < content.length; index += 1) {
    const char = content[index]

    if (char === "\"") {
      const next = content[index + 1]
      if (inQuotes && next === "\"") {
        field += "\""
        index += 1
      } else {
        inQuotes = !inQuotes
      }
      continue
    }

    if (char === "," && !inQuotes) {
      row.push(field)
      field = ""
      continue
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && content[index + 1] === "\n") {
        index += 1
      }
      row.push(field)
      if (row.some((cell) => String(cell).trim() !== "")) {
        rows.push(row)
      }
      row = []
      field = ""
      continue
    }

    field += char
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field)
    if (row.some((cell) => String(cell).trim() !== "")) {
      rows.push(row)
    }
  }

  return rows
}

function headerIndex(header, ...candidates) {
  for (const candidate of candidates) {
    const found = header.indexOf(candidate)
    if (found >= 0) {
      return found
    }
  }
  return -1
}

function normalizeImageName(rawValue) {
  const clean = String(rawValue ?? "").trim().replaceAll("\\", "/")
  const file = basename(clean)
  if (!file) {
    return ""
  }
  // Fix common accidental typo from CSV editors: "toy,jpg" -> "toy.jpg"
  if (!file.includes(".") && file.includes(",")) {
    return file.replace(",", ".")
  }
  return file
}

function splitExtension(fileName) {
  const lastDot = fileName.lastIndexOf(".")
  if (lastDot <= 0 || lastDot === fileName.length - 1) {
    return { stem: fileName, ext: "" }
  }
  return {
    stem: fileName.slice(0, lastDot),
    ext: fileName.slice(lastDot).toLowerCase(),
  }
}

function listKnownImages(dirPath) {
  const supported = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"])
  const names = []
  for (const entry of readdirSync(dirPath)) {
    const parsed = splitExtension(entry)
    if (!supported.has(parsed.ext)) {
      continue
    }
    names.push(entry)
  }
  return names
}

function buildHarajBankTs(products) {
  const lines = []
  lines.push("export type HarajProduct = {")
  lines.push("  id: string")
  lines.push("  name: string")
  lines.push("  imageUrl: string")
  lines.push("  actualPrice: number")
  lines.push('  currency: "SAR"')
  lines.push("}")
  lines.push("")
  lines.push("// Generated by scripts/sync-haraj-products-from-csv.mjs from haraj.csv")
  lines.push("export const HARAJ_PRODUCT_BANK: HarajProduct[] = [")

  for (const product of products) {
    lines.push("  {")
    lines.push(`    id: ${JSON.stringify(product.id)},`)
    lines.push(`    name: ${JSON.stringify(product.name)},`)
    lines.push(`    imageUrl: ${JSON.stringify(product.imageUrl)},`)
    lines.push(`    actualPrice: ${product.actualPrice},`)
    lines.push('    currency: "SAR",')
    lines.push("  },")
  }

  lines.push("]")
  lines.push("")
  return `${lines.join("\n")}`
}

const raw = readFileSync(csvPath, "utf8")
const rows = parseCsv(raw)

if (rows.length < 2) {
  console.error(`CSV ${csvPath} has no data rows.`)
  process.exit(1)
}

const header = rows[0].map((value) => String(value).replace(/^\uFEFF/, "").trim().toLowerCase())
const nameIndex = headerIndex(header, "product name", "name", "product")
const priceIndex = headerIndex(header, "price", "actualprice", "actual price")
const imageIndex = headerIndex(header, "image", "image name", "image file", "image filename")

if (nameIndex < 0 || priceIndex < 0 || imageIndex < 0) {
  console.error(`CSV header must include Product name, Price, image. Found: ${header.join(", ")}`)
  process.exit(1)
}

const products = []
const warnings = []
const knownImages = listKnownImages(imageDirPath)
const byExactLower = new Map(knownImages.map((name) => [name.toLowerCase(), name]))
const byStemLower = new Map()
for (const imageName of knownImages) {
  const { stem } = splitExtension(imageName)
  const key = stem.toLowerCase()
  const list = byStemLower.get(key) ?? []
  list.push(imageName)
  byStemLower.set(key, list)
}

function resolveImageFileName(rawImageName, rowNumber) {
  const provided = normalizeImageName(rawImageName)
  if (!provided) {
    return ""
  }

  const { stem } = splitExtension(provided)
  const stemMatches = byStemLower.get(stem.toLowerCase()) ?? []
  const webpMatch = stemMatches.find((name) => splitExtension(name).ext === ".webp")
  if (webpMatch) {
    const providedExt = splitExtension(provided).ext
    if (providedExt !== ".webp") {
      warnings.push(`Row ${rowNumber}: preferred "${webpMatch}" over "${provided}" for optimized runtime asset.`)
    }
    return webpMatch
  }

  const exact = byExactLower.get(provided.toLowerCase())
  if (exact) {
    return exact
  }

  const byStem = stemMatches
  if (byStem.length === 1) {
    warnings.push(
      `Row ${rowNumber}: image "${provided}" not found exactly, auto-resolved to "${byStem[0]}" from image directory.`
    )
    return byStem[0]
  }
  if (byStem.length > 1) {
    const preferredOrder = [".webp", ".jpg", ".jpeg", ".png", ".gif"]
    byStem.sort((a, b) => {
      const extA = splitExtension(a).ext
      const extB = splitExtension(b).ext
      return preferredOrder.indexOf(extA) - preferredOrder.indexOf(extB)
    })
    warnings.push(
      `Row ${rowNumber}: image "${provided}" matched multiple files, selected "${byStem[0]}".`
    )
    return byStem[0]
  }

  warnings.push(`Row ${rowNumber}: image "${provided}" not found under ${imageDirArg}.`)
  return provided
}

for (let rowIndex = 1; rowIndex < rows.length; rowIndex += 1) {
  const row = rows[rowIndex]
  const name = String(row[nameIndex] ?? "").trim()
  const rawPrice = row[priceIndex] ?? ""
  const imageName = resolveImageFileName(row[imageIndex] ?? "", rowIndex + 1)
  const actualPrice = parseNumber(rawPrice)

  if (!name) {
    warnings.push(`Row ${rowIndex + 1}: missing product name, skipped.`)
    continue
  }
  if (!Number.isFinite(actualPrice) || actualPrice < 0) {
    warnings.push(`Row ${rowIndex + 1}: invalid price "${rawPrice}", skipped.`)
    continue
  }
  if (!imageName) {
    warnings.push(`Row ${rowIndex + 1}: missing image filename, skipped.`)
    continue
  }

  products.push({
    id: `haraj-csv-${String(products.length + 1).padStart(3, "0")}`,
    name,
    imageUrl: `/images/haraj/${imageName}`,
    actualPrice,
  })
}

if (products.length === 0) {
  console.error("No valid products parsed from CSV.")
  process.exit(1)
}

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, buildHarajBankTs(products), "utf8")

console.log(`Generated ${products.length} Haraj products into ${outputPath}`)
if (warnings.length > 0) {
  console.warn(`Warnings (${warnings.length}):`)
  for (const warning of warnings) {
    console.warn(`- ${warning}`)
  }
}
